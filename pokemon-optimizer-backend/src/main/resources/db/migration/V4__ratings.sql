-- Star ratings from the feedback dialog. Anonymous like feedback: no Trainer is stored.
-- INTEGER, not SMALLINT: ddl-auto=validate expects INTEGER for the entity's int field.
CREATE TABLE rating (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stars      INTEGER NOT NULL CHECK (stars BETWEEN 1 AND 5),
    page       VARCHAR(200),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
