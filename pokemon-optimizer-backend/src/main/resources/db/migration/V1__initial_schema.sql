-- The schema ddl-auto=update had built before Flyway took over. Databases from that time are
-- baselined at this version (spring.flyway.baseline-on-migrate), so this only runs on a new database.

CREATE TABLE trainer (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    google_id VARCHAR(255) NOT NULL UNIQUE,
    name      VARCHAR(255)
);

CREATE TABLE caught_pokemon (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trainer_id    BIGINT NOT NULL REFERENCES trainer (id),
    species_id    VARCHAR(255),
    atk_iv        INTEGER NOT NULL,
    def_iv        INTEGER NOT NULL,
    sta_iv        INTEGER NOT NULL,
    level         DOUBLE PRECISION NOT NULL,
    fast_move     VARCHAR(255),
    charged_move1 VARCHAR(255),
    charged_move2 VARCHAR(255),
    shadow        BOOLEAN NOT NULL DEFAULT FALSE
);
