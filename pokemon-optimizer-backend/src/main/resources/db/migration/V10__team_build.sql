-- One row per finished Team Builder run: the "teams built" total, and usage over time.
-- Anonymous like rating: no Trainer, no Pokémon, no IP. INTEGER for the entity's int field (ddl-auto=validate).
CREATE TABLE team_build (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    league        VARCHAR(20)  NOT NULL,
    cup           VARCHAR(128),
    pokemon_count INTEGER      NOT NULL,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL
);
