-- Battle history (issue #120): every finished battle analysis, and who it belongs to.
-- battle_logs is the analysis itself: the analysis job's id, the teams it saw, the score, outcome and metrics, and
-- the whole result (turn log + report) so the review still opens after the analysis service forgets it (one day).
CREATE TABLE battle_logs (
    match_id                UUID PRIMARY KEY,
    created_at              TIMESTAMPTZ  NOT NULL,
    detected_user_team      TEXT[]       NOT NULL,
    detected_opp_team       TEXT[]       NOT NULL,
    overall_execution_score NUMERIC(4,1) NOT NULL,
    tier                    VARCHAR(16)  NOT NULL,
    outcome                 VARCHAR(4)   CHECK (outcome IN ('WIN', 'LOSS')),   -- null: the recording stopped early
    turns_lost              INTEGER,
    shield_efficiency_pct   NUMERIC(4,1),                                   -- null: no shield used
    timing_accuracy_pct     NUMERIC(4,1),                                   -- null: no throw had an alignment
    timing_errors           INTEGER      NOT NULL,
    mismanaged_shields      INTEGER      NOT NULL,
    suboptimal_switches     INTEGER      NOT NULL,
    suboptimal_charges      INTEGER      NOT NULL,
    result                  JSONB        NOT NULL
);

-- Whose battle it is: a Trainer's, or a guest's (the random token their browser keeps) until they log in and claim it.
CREATE TABLE user_match_history (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    match_id    UUID        NOT NULL UNIQUE REFERENCES battle_logs (match_id) ON DELETE CASCADE,
    trainer_id  BIGINT      REFERENCES trainer (id),
    guest_token UUID,
    recorded_at TIMESTAMPTZ NOT NULL,
    CHECK (trainer_id IS NOT NULL OR guest_token IS NOT NULL)
);
CREATE INDEX user_match_history_trainer ON user_match_history (trainer_id, recorded_at);
CREATE INDEX user_match_history_guest ON user_match_history (guest_token);
